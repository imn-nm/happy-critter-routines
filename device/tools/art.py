#!/usr/bin/env python3
"""The shop's scene as C data (Figma "Scene · Shop", 609:2719).

    python device/tools/art.py   -> ../app/assets/art/art_data.c + art_data.h

Sources, checked in under tools/art/:
  - shop_scene.png  Figma "Field Kit / Scene · Shop · Solid" (1014:4299) at 466 x 466, placed 30 px down
                    as in "Rewards · Shop" (1079:5120)
  - shop_scene_open.png  the same with the two shelf planks taken out (the wall carries on behind):
                    the shelves are drawn by pages.c, one under each row, so they can scroll

The rewards on the shelves are line icons (Iconly, via tools/icons.mjs), not pictures. The scene
is sampled at the LED dot centres (3.8 px pitch from the middle) into a palette-index grid that
pet/led.c draws, so it is 15 KB instead of 400, and lights up the same way as Biscuit's rooms.
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'art')
OUT = os.path.join(HERE, '..', 'app', 'assets', 'art')

PITCH = 3.8
# the scene's colours (Figma vector names), index 0 = nothing
PALETTE = [0x000000, 0x3D2F5E, 0x30254B, 0xB9AD94, 0x65CDAA, 0x879BFF, 0xEAB5DE, 0xFF8F91, 0xFAB047,
           0x729FE3, 0x4F7AC4, 0x3A5AA0, 0x24305A, 0x2C457A]   # the shelves are blue in the file (named as wood)
WALLS = {1, 2}      # soft wall dots; the rest are features


def c_bytes(name, data, per=24):
    lines = []
    for i in range(0, len(data), per):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + per]) + ',')
    return f'static const uint8_t {name}[{len(data)}] = {{\n' + '\n'.join(lines) + '\n};\n'


def nearest(rgb):
    r, g, b = rgb
    if r + g + b < 3 * 48:   # unlit (the LED field's own dark dots) or black
        return 0
    best, bd = 0, 1 << 30
    for i, c in enumerate(PALETTE):
        if i == 0:
            continue
        cr, cg, cb = c >> 16, (c >> 8) & 255, c & 255
        d = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2
        if d < bd:
            best, bd = i, d
    return best if bd < 60 ** 2 else 0


def scene():
    im = Image.open(os.path.join(SRC, 'shop_scene_open.png')).convert('RGBA')
    bg = Image.new('RGBA', im.size, (4, 6, 5, 255))
    bg.alpha_composite(im)
    im = bg.convert('RGB')
    n = int(233 / PITCH + 0.999)   # cells each side of the middle
    side = 2 * n + 1
    room = bytearray(side * side)
    walls = bytearray(side * side)
    for j in range(-n, n + 1):
        for i in range(-n, n + 1):
            cx, cy = 233 + i * PITCH, 233 + j * PITCH
            if (cx - 233) ** 2 + (cy - 233) ** 2 > 231 ** 2:
                continue
            # the brightest pixel in the dot (the dot's middle is its true colour)
            best = (0, 0, 0)
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    p = im.getpixel((int(cx + dx), int(cy + dy)))
                    if sum(p) > sum(best):
                        best = p
            k = nearest(best)
            idx = (j + n) * side + (i + n)
            if k in WALLS:
                walls[idx] = k
            else:
                room[idx] = k
    return side, n, room, walls


def main():
    os.makedirs(OUT, exist_ok=True)
    side, n, room, walls = scene()
    c = '/* Generated by device/tools/art.py. Do not edit. */\n#include "art_data.h"\n\n'
    c += 'const uint32_t shop_palette[] = {\n    ' + ', '.join(f'0x{v:06X}' for v in PALETTE) + '\n};\n\n'
    c += c_bytes('shop_room_map', room) + c_bytes('shop_walls_map', walls)
    c += f'const uint8_t *const shop_room = shop_room_map;\nconst uint8_t *const shop_walls = shop_walls_map;\n'
    c += f'const int shop_side = {side};\nconst int shop_center = {n};\n'
    h = '''/* Generated by device/tools/art.py. Do not edit. */
#pragma once
#include "lvgl.h"

/* Figma "Scene · Shop": a palette-index grid at the LED pitch, drawn by pet/led.c */
extern const uint32_t shop_palette[];
extern const uint8_t *const shop_room;
extern const uint8_t *const shop_walls;
extern const int shop_side, shop_center;
'''
    open(os.path.join(OUT, 'art_data.c'), 'w').write(c)
    open(os.path.join(OUT, 'art_data.h'), 'w').write(h)
    print(f'shop grid {side} x {side}')


if __name__ == '__main__':
    main()
