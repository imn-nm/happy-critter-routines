#!/usr/bin/env python3
"""The shop's pictures and scene as C data (Figma "Reward art" and "Scene · Shop", 609:2719).

    python device/tools/art.py   -> ../app/assets/art/art_data.c + art_data.h

Sources, checked in under tools/art/:
  - reward_art.png  the four 72 px pictures (ice cream, book, movie, surprise), rendered from Figma
                    "Reward art" (752:4632) at 1x: a 410 x 122 strip with a picture every 96 px from x 25
  - shop_scene.png  Figma "Field Kit / Scene · Shop" (754:4653) rendered at 466 x 466

The pictures become ARGB8888 LVGL images. The scene is sampled at the LED dot centres (3.8 px
pitch from the middle) into a palette-index grid that pet/led.c draws, so it is 15 KB instead of
400, and lights up the same way as Biscuit's rooms.
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'art')
OUT = os.path.join(HERE, '..', 'app', 'assets', 'art')

ART = [('icecream', 25), ('book', 121), ('film', 217), ('gift', 313)]
PITCH = 3.8
# the scene's colours (Figma vector names), index 0 = nothing
PALETTE = [0x000000, 0x3D2F5E, 0x30254B, 0xB9AD94, 0x65CDAA, 0x879BFF, 0xEAB5DE, 0xFF8F91, 0xFAB047,
           0x729FE3, 0x4F7AC4, 0x3A5AA0, 0x24305A, 0x2C457A]   # the shelves are blue in the file (named as wood)
WALLS = {1, 2}      # soft wall dots; the rest are features


def c_bytes(name, data, per=24):
    lines = []
    for i in range(0, len(data), per):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + per]) + ',')
    return f'static const uint8_t {name}[{len(data)}] = {{\n' + '\n'.join(lines) + '\n};\n'


def pictures():
    strip = Image.open(os.path.join(SRC, 'reward_art.png')).convert('RGBA')
    out = ''
    for name, x in ART:
        im = strip.crop((x, 25, x + 72, 25 + 72))
        data = bytearray()
        for px in im.get_flattened_data() if hasattr(im, 'get_flattened_data') else im.getdata():
            r, g, b, a = px
            # the components sit on the kit's sunken colour (#0E1221): key it out, soft at the edges
            d = abs(r - 14) + abs(g - 18) + abs(b - 33)
            if d < 24:
                a = 0
            elif d < 72:
                a = (d - 24) * 255 // 48
            data += bytes((b, g, r, a))   # LVGL ARGB8888 is little-endian BGRA in memory
        out += c_bytes(f'art_{name}_map', data, 36)
        out += (f'static const lv_image_dsc_t art_{name} = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, '
                f'.cf = LV_COLOR_FORMAT_ARGB8888, .w = 72, .h = 72, .stride = 72 * 4 }}, .data_size = 72 * 72 * 4, '
                f'.data = art_{name}_map }};\n\n')
    return out


def nearest(rgb):
    r, g, b = rgb
    if r + g + b < 3 * 48:   # unlit (the LED field's own dark dots) or black
        return 0
    best, bd = 0, 1 << 30
    for i, c in enumerate(PALETTE):
        if i == 0:
            continue
        cr, cg, cb = c >> 16, (c >> 8) & 255, c & 255
        d = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2
        if d < bd:
            best, bd = i, d
    return best if bd < 60 ** 2 else 0


def scene():
    im = Image.open(os.path.join(SRC, 'shop_scene.png')).convert('RGBA')
    bg = Image.new('RGBA', im.size, (4, 6, 5, 255))
    bg.alpha_composite(im)
    im = bg.convert('RGB')
    n = int(233 / PITCH + 0.999)   # cells each side of the middle
    side = 2 * n + 1
    room = bytearray(side * side)
    walls = bytearray(side * side)
    for j in range(-n, n + 1):
        for i in range(-n, n + 1):
            cx, cy = 233 + i * PITCH, 233 + j * PITCH
            if (cx - 233) ** 2 + (cy - 233) ** 2 > 231 ** 2:
                continue
            # the brightest pixel in the dot (the dot's middle is its true colour)
            best = (0, 0, 0)
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    p = im.getpixel((int(cx + dx), int(cy + dy)))
                    if sum(p) > sum(best):
                        best = p
            k = nearest(best)
            idx = (j + n) * side + (i + n)
            if k in WALLS:
                walls[idx] = k
            else:
                room[idx] = k
    return side, n, room, walls


def main():
    os.makedirs(OUT, exist_ok=True)
    side, n, room, walls = scene()
    c = '/* Generated by device/tools/art.py. Do not edit. */\n#include "art_data.h"\n\n'
    c += pictures()
    c += 'const art_entry_t art_table[] = {\n' + ''.join(f'    {{ "{name}", &art_{name} }},\n' for name, _ in ART) + '};\n'
    c += f'const int art_table_count = {len(ART)};\n\n'
    c += 'const uint32_t shop_palette[] = {\n    ' + ', '.join(f'0x{v:06X}' for v in PALETTE) + '\n};\n\n'
    c += c_bytes('shop_room_map', room) + c_bytes('shop_walls_map', walls)
    c += f'const uint8_t *const shop_room = shop_room_map;\nconst uint8_t *const shop_walls = shop_walls_map;\n'
    c += f'const int shop_side = {side};\nconst int shop_center = {n};\n'
    h = '''/* Generated by device/tools/art.py. Do not edit. */
#pragma once
#include "lvgl.h"

typedef struct { const char *name; const lv_image_dsc_t *img; } art_entry_t;
extern const art_entry_t art_table[];
extern const int art_table_count;

/* Figma "Scene · Shop": a palette-index grid at the LED pitch, drawn by pet/led.c */
extern const uint32_t shop_palette[];
extern const uint8_t *const shop_room;
extern const uint8_t *const shop_walls;
extern const int shop_side, shop_center;
'''
    open(os.path.join(OUT, 'art_data.c'), 'w').write(c)
    open(os.path.join(OUT, 'art_data.h'), 'w').write(h)
    print(f'{len(ART)} pictures, shop grid {side} x {side}')


if __name__ == '__main__':
    main()
