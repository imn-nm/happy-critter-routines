function lucideSvg(name) {
  const src = fs.readFileSync(path.join(LUCIDE, name + '.js'), 'utf8');
  const m = src.match(/createLucideIcon\("[^"]*", (\[[\s\S]*?\])\);/);
  if (!m) throw new Error('cannot read lucide ' + name);
  const nodes = Function('return ' + m[1])();
  const body = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#FFFFFF" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

const icons = new Map();
// The kit's star is filled (ratings); task icons use the outline "star-line".
for (const f of fs.readdirSync(FK).filter(f => f.endsWith('.svg'))) icons.set(f === 'star.svg' ? 'star-fill' : f.slice(0, -4), fs.readFileSync(path.join(FK, f), 'utf8'));
for (const [name, lucide] of Object.entries(FROM_LUCIDE)) if (!icons.has(name)) icons.set(name, lucideSvg(lucide));
for (const [k, v] of Object.entries(ALIASES)) if (!icons.has(v)) throw new Error(`alias ${k} -> missing icon ${v}`);

const cname = (n) => n.replace(/[^a-z0-9]/g, '_');
let c = `/* Generated by device/tools/icons.mjs. Do not edit. */\n#include "icons_data.h"\n\n`;
const table = [];
let bytes = 0;
for (const [name, svg] of [...icons].sort()) {
  for (const size of SIZES) {
    const png = new Resvg(svg, { fitTo: { mode: 'width', value: size }, background: 'rgba(0,0,0,0)', font: { loadSystemFonts: false } }).render();
    const { width: w, height: h, pixels } = png;
    const a = new Uint8Array(w * h);
    for (let i = 0; i < w * h; i++) a[i] = pixels[i * 4 + 3];
    const id = `ic_${cname(name)}_${size}`;
    c += `static const uint8_t ${id}_map[${w * h}] = {${Array.from(a, (v, i) => (i % 32 ? '' : '\n    ') + v).join(',')}\n};\n`;
    c += `static const lv_image_dsc_t ${id} = { .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = ${w}, .h = ${h}, .stride = ${w} }, .data_size = ${w * h}, .data = ${id}_map };\n\n`;
    table.push(`    { "${name}", ${size}, &${id} },`);
    bytes += w * h;
  }
}
c += `const icon_entry_t icon_table[] = {\n${table.join('\n')}\n};\nconst int icon_table_count = ${table.length};\n\n`;
c += `const icon_alias_t icon_aliases[] = {\n${Object.entries(ALIASES).map(([k, v]) => `    { "${k}", "${v}" },`).join('\n')}\n};\nconst int icon_alias_count = ${Object.keys(ALIASES).length};\n`;
const h = `/* Generated by device/tools/icons.mjs. Do not edit. */
#pragma once
#include "lvgl.h"

typedef struct { const char *name; uint8_t size; const lv_image_dsc_t *img; } icon_entry_t;
typedef struct { const char *key; const char *name; } icon_alias_t;
extern const icon_entry_t icon_table[];
extern const int icon_table_count;
extern const icon_alias_t icon_aliases[];
extern const int icon_alias_count;
`;
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'icons_data.c'), c);
fs.writeFileSync(path.join(OUT, 'icons_data.h'), h);
console.log(`${icons.size} icons x ${SIZES.length} sizes, ${(bytes / 1024).toFixed(0)} KB of masks`);
