// Converts the MyToki 2 typefaces into LVGL bitmap fonts at the sizes the screens use.
//   node fonts.mjs   -> ../app/assets/fonts/*.c + fonts.h
// Needs the static TTF instances that setup.py makes in ../.tools/fonts (Space Grotesk and Montserrat
// are variable fonts upstream; Poppins is static). All are SIL Open Font License.
import { execFileSync } from 'child_process';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';
// opentype.js comes with lv_font_conv.

const require = createRequire(path.join(path.dirname(fileURLToPath(import.meta.url)), 'node_modules', 'lv_font_conv', 'package.json'));
const opentype = require('opentype.js');

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(HERE, '../.tools/fonts');
const OUT = path.resolve(HERE, '../app/assets/fonts');
const CONV = path.join(HERE, 'node_modules', 'lv_font_conv', 'lv_font_conv.js');

// Text: ASCII, Latin-1 (names like Zoë, José), curly quotes, dashes, the ellipsis, bullets, arrows.
const TEXT = ['0x20-0x7E', '0xA0-0xFF', '0x2013-0x2014', '0x2018-0x201D', '0x2022', '0x2026', '0x2192'];
const DIGITS = ['0x20', '0x30-0x3A', '0x61', '0x6D', '0x70']; // " 0-9:" plus "a m p" for am/pm

// [file, weight label, sizes, ranges]
const FONTS = [
  // MyToki 2 (Figma "Child UI · New UI", 1052:5356), the "MyToki 2/" text styles:
  // Title 30 in Poppins Bold (Figma "MyToki 2 / Header", 1070:4496); Display 32 in Montserrat Bold, Message 21 in Montserrat Medium, Big number 52 (digits);
  // Poppins Body 22, Pill 24, Detail/Speech 20, the header's clock 18 (Medium), Item 24, the picture view's row now 32
  // and Label 20 (SemiBold), Button 22;
  // the Next block in Space Grotesk: Next label 22 (Medium), Next time 22 and Next task 24 (Bold).
  ['Montserrat-700.ttf', 'mon700', [26, 32], TEXT],
  ['Montserrat-600.ttf', 'mon600', [52], DIGITS],
  ['Montserrat-500.ttf', 'mon500', [21], TEXT],
  ['Poppins-500.ttf', 'pop500', [18, 20, 22, 24], TEXT],
  ['Poppins-600.ttf', 'pop600', [20, 22, 24, 32], TEXT],
  ['Poppins-700.ttf', 'pop700', [22, 24, 30], TEXT],
  ['SpaceGrotesk-500.ttf', 'sg500', [22], TEXT],
  ['SpaceGrotesk-700.ttf', 'sg700', [22, 24], TEXT],
];

fs.mkdirSync(OUT, { recursive: true });
const names = [];
for (let [file, label, sizes, ranges] of FONTS) {
  const ttf = path.join(SRC, file);
  if (!fs.existsSync(ttf)) throw new Error(`missing ${ttf}: run python device/tools/setup.py`);
  // lv_font_conv refuses a range the font has nothing in (Amiko has no arrow).
  const font = opentype.loadSync(ttf);
  const has = (r) => { const [a, b = a] = r.split('-').map(Number); for (let c = a; c <= b; c++) if (font.charToGlyphIndex(String.fromCodePoint(c))) return true; return false; };
  ranges = ranges.filter(has);
  for (const size of sizes) {
    const name = `font_${label}_${size}`;
    const out = path.join(OUT, name + '.c');
    const args = [CONV, '--font', ttf, '--size', String(size), '--bpp', '4', '--format', 'lvgl', '--no-compress',
      '--lv-font-name', name, '--lv-include', 'lvgl.h', '-o', out];
    for (const r of ranges) args.splice(3, 0, '-r', r);
    execFileSync(process.execPath, args, { stdio: 'inherit' });
    names.push(name);
  }
}
const h = `/* Generated by device/tools/fonts.mjs. Do not edit. */
#pragma once
#include "lvgl.h"

${names.map(n => `LV_FONT_DECLARE(${n});`).join('\n')}
`;
fs.writeFileSync(path.join(OUT, 'fonts.h'), h);
console.log(`${names.length} fonts -> ${path.relative(process.cwd(), OUT)}`);
