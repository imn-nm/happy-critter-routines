export const textWidth = (s: string) => [...s].reduce((w, ch) => w + (FONT[ch] ? FONT[ch][0].length : 2) + 1, -1);

export function text(p: Pix, s: string, x: number, y: number, color: string) {
  for (const ch of s) {
    const g = FONT[ch];
    if (g) {
      p.stamp(g, x, y, color);
      x += g[0].length + 1;
    } else x += 3;
  }
}

/** A white speech bubble with its tail pointing down-left at the speaker. */
export function bubble(p: Pix, s: string, x: number, y: number) {
  const w = textWidth(s) + 6, h = 11;
  for (let yy = 0; yy < h; yy++) {
    for (let xx = 0; xx < w; xx++) {
      if (!((xx === 0 || xx === w - 1) && (yy === 0 || yy === h - 1))) p.set(x + xx, y + yy, "H");
    }
  }
  p.set(x + 1, y + h, "H"); p.set(x + 2, y + h, "H"); p.set(x, y + h + 1, "H"); p.set(x - 1, y + h + 2, "H");
  text(p, s, x + 3, y + 3, "h");
  return w;
}
